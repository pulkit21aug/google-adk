package com.pulsdaily.oncology.model;

public class PatientInfo   {

    public String getPatientId() {
        return patientId;
    }

    public void setPatientId(String patientId) {
        this.patientId = patientId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public String getGender() {
        return gender;
    }

    public void setGender(String gender) {
        this.gender = gender;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getAttendentName() {
        return attendentName;
    }

    public void setAttendentName(String attendentName) {
        this.attendentName = attendentName;
    }

    public String getAttendentPhone() {
        return attendentPhone;
    }

    public void setAttendentPhone(String attendentPhone) {
        this.attendentPhone = attendentPhone;
    }

    public String getAttendentRelationship() {
        return attendentRelationship;
    }

    public void setAttendentRelationship(String attendentRelationship) {
        this.attendentRelationship = attendentRelationship;
    }

    public String getPatientDoctor() {
        return patientDoctor;
    }

    public void setPatientDoctor(String patientDoctor) {
        this.patientDoctor = patientDoctor;
    }

    public String getDoctorId() {
        return doctorId;
    }

    public void setDoctorId(String doctorId) {
        this.doctorId = doctorId;
    }

    public String getInsuranceProvider() {
        return insuranceProvider;
    }

    public void setInsuranceProvider(String insuranceProvider) {
        this.insuranceProvider = insuranceProvider;
    }

    public String getInsuranceType() {
        return insuranceType;
    }

    public void setInsuranceType(String insuranceType) {
        this.insuranceType = insuranceType;
    }

    public String getPreApprovalStatus() {
        return preApprovalStatus;
    }

    public void setPreApprovalStatus(String preApprovalStatus) {
        this.preApprovalStatus = preApprovalStatus;
    }

    private String patientId;
    private String name;
    private int age;
    private String gender;
    private String address;
    private String email;
    private String phone;
    private String attendentName;
    private String attendentPhone;
    private String attendentRelationship;
    private String patientDoctor;
    private String doctorId;
    private String insuranceProvider;
    private String insuranceType;
    private String preApprovalStatus;


}
